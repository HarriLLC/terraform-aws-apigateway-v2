#!/bin/sh
# Validate the module, once per turn.
#
# The repo root is validated when it holds .tf files, then every submodule under
# modules/<name>/ on its own. Validating the root only checks the submodules it
# calls; one that only a wrapper or a consumer calls (via //modules/<name>) would
# otherwise never be checked. A mono-repo with no .tf at the root is validated
# one submodule at a time. When the root fails, its submodules and wrappers are
# skipped for that turn, since the same error would repeat through them; a
# wrapper is skipped the same way when the submodule it wraps failed.
#
# A wrapper module is never called by the root, so validating the root does not
# check it. When the repo has wrappers/ (optional, generated by the pre-commit
# hook terraform_wrapper_module_for_each), wrappers/ and each wrappers/<name>/ are
# validated on their own, which catches a root input that was renamed or removed.
# A new input that is missing from a wrapper is still valid HCL, so each wrapper
# is also checked to pass every variable of the module it wraps.
#
# A module has no backend, so `terraform init` only installs providers and
# modules and never touches HCP. It runs only when `.terraform/` is missing, or
# when validate fails (a new provider or module may need installing), and then
# validate is retried once.
#
# Validate always runs, even if init failed: a syntax error makes init fail too,
# and skipping on that would hide the error. Only a result that just says init is
# missing (offline, no registry access) is treated as a setup problem and skipped.
#
# A module holds no state, so `plan` and `apply` never run here. Errors go to
# stderr with exit 2, so Claude sees them and fixes the file.
grep -q '"stop_hook_active": *true' && exit 0      # already ran for this stop
command -v terraform >/dev/null 2>&1 || exit 0
cd "${CLAUDE_PROJECT_DIR:-.}" 2>/dev/null || exit 0

# Each validated directory needs its own init. A shared plugin cache downloads
# each provider once instead of once per directory. A cache the user already set
# is kept.
if [ -z "$TF_PLUGIN_CACHE_DIR" ]; then
  TF_PLUGIN_CACHE_DIR="$HOME/.terraform.d/plugin-cache"
  mkdir -p "$TF_PLUGIN_CACHE_DIR" 2>/dev/null && export TF_PLUGIN_CACHE_DIR || unset TF_PLUGIN_CACHE_DIR
fi

regen='wrappers/ is generated; regenerate it with: pre-commit run terraform_wrapper_module_for_each -a'

has_tf() { ls "$1"/*.tf >/dev/null 2>&1; }

check() {
  init() { iout=$(cd "$1" && terraform init -upgrade -no-color -input=false 2>&1); }
  iout=""
  [ -d "$1/.terraform" ] || init "$1"
  out=$(cd "$1" && terraform validate -no-color 2>&1) && return 0
  init "$1" && out=$(cd "$1" && terraform validate -no-color 2>&1) && return 0
  if printf '%s\n' "$out" | grep -qiE 'run "terraform init"|Module not installed|Missing required provider|Required plugins are not installed'; then
    # validate could not run because init did not complete. Init stops on a
    # config error too (e.g. an argument the called module no longer accepts);
    # report that one. A network or registry failure is a setup problem: skip.
    printf '%s\n' "$iout" | grep -q 'Error:' || return 0
    printf '%s\n' "$iout" | grep -qiE 'Failed to query|Failed to install|Failed to download|could not connect|dial tcp|no such host|i/o timeout|TLS handshake|credentials|unauthorized|forbidden' && return 0
    out=$(printf '%s\n' "$iout" | sed -n '/Error:/,$p')
  fi
  printf -- '--- %s\n%s\n' "$1" "$out" >&2
  case "$1" in wrappers|wrappers/*) printf '%s\n' "$regen" >&2 ;; esac
  failed="$failed $(cd "$1" && pwd)"
  return 2
}
failed=""

# the directory a wrapper calls, when it is local
wrapped() {
  src=$(sed -n 's/^[[:space:]]*source[[:space:]]*=[[:space:]]*"\(\.[^"]*\)".*/\1/p' "$1/main.tf" 2>/dev/null | head -1)
  [ -n "$src" ] && (cd "$1/$src" 2>/dev/null && pwd)
}

# every variable of the wrapped module must be passed by the wrapper
wrapper_inputs() {
  src=$(sed -n 's/^[[:space:]]*source[[:space:]]*=[[:space:]]*"\(\.[^"]*\)".*/\1/p' "$1/main.tf" 2>/dev/null | head -1)
  [ -n "$src" ] && [ -d "$1/$src" ] || return 0
  missing=""
  for v in $(sed -n 's/^variable[[:space:]]*"\([^"]*\)".*/\1/p' "$1/$src"/*.tf 2>/dev/null); do
    grep -qE "^[[:space:]]*$v[[:space:]]*=" "$1/main.tf" || missing="$missing $v"
  done
  [ -z "$missing" ] && return 0
  printf -- '--- %s\nInputs of %s not passed by the wrapper:%s\n%s\n' "$1" "$src" "$missing" "$regen" >&2
  return 2
}

submodules=$(for d in modules/*/; do d=${d%/}; has_tf "$d" && echo "$d"; done)
wrappers=$(for d in wrappers wrappers/*/; do d=${d%/}; has_tf "$d" && echo "$d"; done)

rc=0
if has_tf .; then check . || rc=2; fi
root_rc=$rc
# a root error would only repeat in the submodules and wrappers it touches
if [ "$root_rc" -eq 0 ]; then
  for d in $submodules; do check "$d" || rc=2; done
fi
for d in $wrappers; do
  wrapper_inputs "$d" || rc=2
  [ "$root_rc" -eq 0 ] || continue
  # the wrapped module already failed: its error would only repeat here
  w=$(wrapped "$d")
  case " $failed " in *" $w "*) [ -n "$w" ] && continue ;; esac
  check "$d" || rc=2
done
exit "$rc"
